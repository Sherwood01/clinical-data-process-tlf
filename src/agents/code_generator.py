    def generate_program(
        self,
        table_id: str,
        table_name: str,
        analysis_set: str,
        group_by: str,
        dataset: str,
        macro_calls: list[dict] = None,
        population_filter: str = "1=1"
    ) -> str:
        """
        Generate a complete SAS TLF program matching reference format.

        Args:
            table_id: Table identifier (e.g., "14.1.1.1")
            table_name: Table name
            analysis_set: Analysis set name
            group_by: Grouping variable (usually treatment)
            dataset: ADaM dataset name
            macro_calls: List of macro call specifications (optional)
            population_filter: Population filter condition

        Returns:
            Generated SAS program code
        """
        from datetime import datetime

        dataset_upper = dataset.upper()

        # Build header
        header = self.HEADER_TEMPLATE.format(
            table_id=table_id,
            table_name=table_name,
            analysis_set=analysis_set,
            group_by=group_by,
            dataset_upper=dataset_upper,
            timestamp=datetime.now().strftime("%Y-%m-%d"),
            data_prep=self.DATA_PREP_TEMPLATE.strip()
        )

        # Build footer
        footer = self.FOOTER_TEMPLATE.format(unit_prefix="unit")

        # 1. 尝试使用大模型进行自适应拼装
        analysis_code = self._generate_with_llm(
            table_id=table_id,
            table_name=table_name,
            analysis_set=analysis_set,
            group_by=group_by,
            dataset=dataset_upper,
            macro_calls=macro_calls,
            population_filter=population_filter
        )
        
        # 2. 多阶专家验证反馈与自我纠错 (Self-Correction)
        validation = self.validate_syntax(header + analysis_code + footer)
        if not validation["valid"]:
            print(f"[CodeGeneratorAgent] Detected syntax errors: {validation['errors']}. Requesting LLM self-correction...")
            analysis_code = self._generate_with_llm_correction(
                table_id=table_id,
                table_name=table_name,
                bad_code=analysis_code,
                errors=validation["errors"]
            )

        # 3. 如果 LLM 生成失败或属于降级标志，则降级使用本地常规规则以确保高可用性
        if "Fallback descriptive code" in analysis_code or not analysis_code.strip():
            if table_id == "14.1.1.1":
                analysis_units = self._generate_14111_units()
            else:
                analysis_units = self._generate_default_units(dataset_upper, group_by)
            analysis_code = "\n".join(analysis_units)

        # Combine
        full_code = header + "\n" + analysis_code + "\n" + footer
        return full_code

