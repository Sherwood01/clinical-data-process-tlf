"""Isolated execution sandbox using dynamic temporary Docker containers or fallback subprocesses.

Provides a secure context to run AI-generated Python plotting and analytical codes,
preventing shell escape, credential leakages, or socket exposure.
"""
import os
import uuid
import shutil
import tempfile
import subprocess
import logging
from pathlib import Path
from typing import Dict, Optional, Tuple

logger = logging.getLogger("ai-sandbox")

try:
    import docker
    from docker.errors import DockerException
except ImportError:
    docker = None
    DockerException = Exception


class SandboxResult:
    """Encapsulates the output and error logs of a sandboxed code execution."""

    def __init__(self, success: bool, stdout: str, stderr: str, file_bytes: Optional[bytes] = None):
        self.success = success
        self.stdout = stdout
        self.stderr = stderr
        self.file_bytes = file_bytes


def run_code_in_sandbox(
    code_str: str,
    datasets: Dict[str, bytes],
    output_filename: str = "output.pdf",
    timeout_seconds: int = 15,
) -> SandboxResult:
    """Run arbitrary Python code securely, passing datasets, and retrieving output file bytes.

    Args:
        code_str: Python source code generated by the LLM Agent.
        datasets: Dict of filename (e.g. 'adsl.sas7bdat') -> raw file bytes.
        output_filename: The target output filename (e.g. 'output.pdf') to recover.
        timeout_seconds: Hard execution limit before killing sandbox container/process.

    Returns:
        A SandboxResult containing status, print logs, error details, and output file bytes.
    """
    # 1. Create a host temporary directory acting as the workspace
    temp_dir = tempfile.mkdtemp(prefix="tlf-sandbox-")
    temp_path = Path(temp_dir)

    try:
        # Write SAS dataset files into the stage area
        for ds_name, ds_bytes in datasets.items():
            # Guard against directory traversal in filenames
            safe_name = os.path.basename(ds_name)
            (temp_path / safe_name).write_bytes(ds_bytes)

        # Write the python script
        script_file = temp_path / "script.py"
        script_file.write_text(code_str, encoding="utf-8")

        # 2. Attempt execution via Docker Container Sandbox
        if docker is not None:
            try:
                result = _run_via_docker(temp_dir, "script.py", output_filename, timeout_seconds)
                if result is not None:
                    return result
            except Exception as e:
                logger.warning(f"Docker sandbox execution failed or unavailable: {e}. Falling back to subprocess.")

        # 3. Fallback execution via restricted Subprocess
        return _run_via_subprocess(temp_dir, "script.py", output_filename, timeout_seconds)

    finally:
        # 4. Thorough cleanup of temporary files from Host
        try:
            shutil.rmtree(temp_dir, ignore_errors=True)
        except Exception as e:
            logger.error(f"Failed to clean up sandbox temporary directory {temp_dir}: {e}")


def _run_via_docker(
    host_dir: str,
    script_name: str,
    output_filename: str,
    timeout_seconds: int,
) -> Optional[SandboxResult]:
    """Execute code inside an ephemeral docker container with strict limits and no network."""
    try:
        client = docker.from_env()
    except Exception as e:
        logger.debug(f"Failed to connect to Docker daemon: {e}")
        return None

    # Bind host workspace directory to /workspace in container
    volumes = {
        host_dir: {
            "bind": "/workspace",
            "mode": "rw"
        }
    }

    container = None
    try:
        # Use python:3.11-slim as standard lightweight Python executor
        image = "python:3.11-slim"

        # Docker resource constraints: 0.5 CPU, 256MB memory, disabled network
        container = client.containers.create(
            image=image,
            command=["python", f"/workspace/{script_name}"],
            network_disabled=True,
            volumes=volumes,
            working_dir="/workspace",
            mem_limit="256m",
            nano_cpus=500000000,  # 0.5 Cores
            user=os.getuid() if hasattr(os, "getuid") else None,  # run as non-root on Unix
        )

        container.start()

        # Wait for execution to finish under timeout limits
        status = container.wait(timeout=timeout_seconds)
        exit_code = status.get("StatusCode", 0)

        # Retrieve stdout and stderr logs combined
        logs = container.logs()
        stdout = logs.decode("utf-8", errors="replace")
        success = (exit_code == 0)

        file_bytes = None
        output_filepath = os.path.join(host_dir, output_filename)
        if success and os.path.exists(output_filepath):
            with open(output_filepath, "rb") as f:
                file_bytes = f.read()

        return SandboxResult(
            success=success,
            stdout=stdout,
            stderr="" if success else f"Exit code: {exit_code}\n{stdout}",
            file_bytes=file_bytes
        )

    except docker.errors.ContainerError as exc:
        return SandboxResult(
            success=False,
            stdout=exc.stderr.decode("utf-8", errors="replace") if exc.stderr else "",
            stderr=str(exc)
        )
    except Exception as e:
        logger.warning(f"Error during docker run sequence: {e}")
        return None
    finally:
        if container:
            try:
                container.remove(force=True)
            except Exception:
                pass


def _run_via_subprocess(
    host_dir: str,
    script_name: str,
    output_filename: str,
    timeout_seconds: int,
) -> SandboxResult:
    """Execute code in a fallback local subprocess with restricted environment variables."""
    # Clean standard env variables (exclude DB connections or API credentials)
    safe_env = {
        "PATH": os.environ.get("PATH", ""),
        "PYTHONPATH": host_dir,
    }

    script_path = os.path.join(host_dir, script_name)
    try:
        proc = subprocess.run(
            ["python", script_path],
            cwd=host_dir,
            timeout=timeout_seconds,
            capture_output=True,
            text=True,
            env=safe_env,
        )

        success = (proc.returncode == 0)
        file_bytes = None
        output_filepath = os.path.join(host_dir, output_filename)

        if success and os.path.exists(output_filepath):
            with open(output_filepath, "rb") as f:
                file_bytes = f.read()

        return SandboxResult(
            success=success,
            stdout=proc.stdout,
            stderr=proc.stderr if not success else "",
            file_bytes=file_bytes
        )
    except subprocess.TimeoutExpired as exc:
        return SandboxResult(
            success=False,
            stdout=exc.stdout if exc.stdout else "",
            stderr=f"Execution timed out after {timeout_seconds} seconds.",
        )
    except Exception as e:
        return SandboxResult(
            success=False,
            stdout="",
            stderr=f"Subprocess launch failed: {str(e)}",
        )
